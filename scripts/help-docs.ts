/**
 * Writes the files that come from the Help pages (plugin/shared/wiki) and the catalog contract, so each fact has one
 * source: docs/help.md (every page), docs/extensions-tutorial.md ("Make your own"), and in marketplace/ the example
 * extension file and index.schema.json. Run `pnpm help:docs` after changing them; tests/wiki.test.ts fails while a
 * file is out of date.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { marketplaceIndexSchema } from "../plugin/shared/marketplace";
import { EXAMPLE_FILE, wikiOutline, wikiPageMarkdown, wikiPages } from "../plugin/shared/wiki";
import { DEFAULT_SHORTCUTS, formatCombo, normalizeCombo } from "../plugin/client/shortcuts";

const keysOf = (id: string) => { const def = DEFAULT_SHORTCUTS.find(s => s.id === id); return def?.keys.length ? def.keys.map(k => formatCombo(normalizeCombo(k), true)).join(" or ") : undefined; };
const note = (source: string) => `<!-- Generated by \`pnpm help:docs\` from ${source}. Edit the source, not this file. -->`;

export function helpMarkdown(): string {
  const sections = wikiOutline(wikiPages).map(section => [`## ${section.title}`, ...section.pages.map(page => wikiPageMarkdown(page, { keysOf, level: 2 }).replace(/\n### /g, "\n#### ").replace(/\n## /g, "\n#### ").replace(/^## /, "### "))].join("\n\n"));
  return [note("plugin/shared/wiki"), "# Lienzo Help", "The pages of Help in the app (menu → Help, ⌘K, or the ? in the Properties panel). Agents read the same pages with `canvas_catalog help`. Shortcuts are the defaults, as on a Mac; Ctrl replaces ⌘ elsewhere.", ...sections].join("\n\n") + "\n";
}
export function tutorialMarkdown(): string {
  const pages = wikiPages.filter(page => page.section === "make");
  return [note("plugin/shared/wiki/tutorial.ts"), "# Make your own Lienzo extension", "The \"Make your own\" walkthrough from Help, step by step, with a complete example. The full contract is in [extensions.md](extensions.md).",
    ...pages.map(page => wikiPageMarkdown(page, { keysOf, level: 2 }).replace(/\n## /g, "\n### ").replace(/^## Make your own/, "## Overview"))].join("\n\n") + "\n";
}
export const exampleFileText = () => JSON.stringify(EXAMPLE_FILE, null, 2);
export const indexSchemaText = () => JSON.stringify({ title: "Lienzo extension index", description: "index.json, built by scripts/build-index.mjs. Generated from plugin/shared/marketplace.ts in github.com/Gabsplat/paseo-canvas.", ...z.toJSONSchema(marketplaceIndexSchema, { io: "input", unrepresentable: "any" }) }, null, 2) + "\n";
export const generated = (root: string): [string, string][] => [
  [join(root, "docs/help.md"), helpMarkdown()], [join(root, "docs/extensions-tutorial.md"), tutorialMarkdown()],
  [join(root, "marketplace/extensions/title-case/extension.json"), exampleFileText()], [join(root, "marketplace/schema/index.schema.json"), indexSchemaText()],
];
if (process.argv[1]?.endsWith("help-docs.ts")) for (const [path, text] of generated(join(import.meta.dirname, ".."))) { writeFileSync(path, text); console.log("Wrote " + path); }
